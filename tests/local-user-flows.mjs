import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
const browser = await chromium.launch({channel:'chrome', headless:true});
const context = await browser.newContext();
const page = await context.newPage();
const username = 'smoke_' + Date.now();
const password = 'Temporary strong smoke password 42!';
const baselineDb = new DatabaseSync('artifacts/community/community.sqlite');
const previousScent = baselineDb.prepare('SELECT scent FROM reviews WHERE spaceSlug=? AND scent IS NOT NULL AND createdAt>=?').all('bpl-central', new Date(Date.now()-60*86400000).toISOString()).map(r=>Number(r.scent));
baselineDb.close();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:3000');
  await page.locator('.space-card').first().waitFor();
  assert.equal(await page.locator('.space-card').count(),29);
  assert.equal(await page.locator('header .brand').innerText(), 'QuietSpace');
  assert.equal(await page.locator('.filters').count(),0);
  assert.ok((await page.locator('#choose-preferences').boundingBox()).y < (await page.getByLabel('Place name or area').boundingBox()).y);
  assert.equal(await page.locator('.intent-check').count(), 0);
  await page.getByRole('button', {name: /Find 29 places with my preferences/}).click();
  assert.equal(await page.locator('#results-heading').evaluate(el => el === document.activeElement), true);
  const counts={};
  for (const label of ['Focus & study','Low stimulation','Space to yourself','Softer lighting','Low fragrance','Comfortable with activity']) {
    const button=page.getByRole('button',{name:new RegExp(label)});
    await button.click();
    await page.getByRole('heading',{name:/Suggested places/}).waitFor();
    const count=await page.locator('.space-card').count();
    assert.ok(count>0&&count<29,label+': '+count); counts[label]=count;
    assert.ok(await page.locator('.suggestion-reason').count()>0);
    await button.click();
  }
  console.log('Preference result counts:',JSON.stringify(counts));
  await page.goto('http://127.0.0.1:3000/spaces/bpl-central/review');
  await page.getByRole('heading',{name:'Sign in to leave a review'}).waitFor();
  const anonymous=await context.request.post('http://127.0.0.1:3000/api/reviews',{headers:{origin:'http://127.0.0.1:3000'},data:{spaceSlug:'bpl-central',rating:4,body:'Automated test text, deleted after verification.'}});
  assert.equal(anonymous.status(),401);
  await page.getByRole('link',{name:'Sign in or create account',exact:true}).click();
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Public display name').fill('Temporary verification account');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Create account & continue'}).click();
  await page.waitForURL('**/spaces/bpl-central/review');
  const invalidAttributes = await context.request.post('http://127.0.0.1:3000/api/reviews', {headers:{origin:'http://127.0.0.1:3000'},data:{spaceSlug:'bpl-central',rating:4,body:'Temporary invalid attribute submission must be rejected.',attributes:{scent:6}}});
  assert.equal(invalidAttributes.status(),400);
  await page.getByRole('group',{name:'Overall experience',exact:true}).getByRole('radio',{name:'4 stars',exact:true}).check();
  for (const [attribute, stars] of [['Quietness',5],['Room to yourself',4],['Softer lighting',3],['Low fragrance',5]]) {
    await page.getByRole('group',{name:new RegExp('^'+attribute+' · optional$')}).getByRole('radio',{name:stars+' stars',exact:true}).check();
  }
  await page.getByLabel('Your review',{exact:true}).fill('Automated flow verification. This temporary review will be deleted immediately.');
  await page.getByRole('button',{name:'Publish review',exact:true}).click();
  await page.getByRole('heading',{name:'Your review is published.'}).waitFor();
  await page.getByRole('link',{name:'See your review'}).click();
  await page.getByText('Automated flow verification.',{exact:false}).waitFor();
  await page.reload();
  await page.getByText('Automated flow verification.',{exact:false}).waitFor();
  const scentSummary = page.locator('.visitor-rating-summary [data-attribute=scent]');
  assert.ok((await scentSummary.innerText()).includes(((previousScent.reduce((sum,n)=>sum+n,0)+5)/(previousScent.length+1)).toFixed(1)));
  assert.ok((await scentSummary.innerText()).includes((previousScent.length+1)+' rating'));
  await page.goto('http://127.0.0.1:3000');
  await page.getByRole('button',{name:/Low fragrance/}).click();
  const centralCard = page.locator('.space-card').filter({has:page.locator('h3 a[href="/spaces/bpl-central"]')});
  const expectedFit = Math.round((1-(5-(previousScent.reduce((sum,n)=>sum+n,0)+5)/(previousScent.length+1))/4)*100);
  if (!await centralCard.count()) await page.getByRole('button',{name:/Show all/}).click();
  assert.ok((await centralCard.innerText()).includes(expectedFit+'% visitor-reported fit'));
  await page.getByRole('button',{name:/Low fragrance/}).click();
  await page.goto('http://127.0.0.1:3000/spaces/bpl-central');
  await page.getByRole('button',{name:'Delete my review',exact:true}).click();
  await page.getByText('Automated flow verification.',{exact:false}).waitFor({state:'detached'});
  if (!previousScent.length) {
    const remaining = page.locator('.visitor-rating-summary [data-attribute=scent]');
    if (await remaining.count()) assert.match(await remaining.innerText(), /Not rated/);
  }
  else assert.ok((await page.locator('.visitor-rating-summary [data-attribute=scent]').innerText()).includes((previousScent.reduce((sum,n)=>sum+n,0)/previousScent.length).toFixed(1)));
  await page.goto('http://127.0.0.1:3000/preferences');
  assert.equal(await page.getByLabel('Step-free access', {exact:true}).count(),0);
  assert.equal(await page.getByLabel('Accessible toilet', {exact:true}).count(),0);
  await page.getByLabel('Noise',{exact:true}).selectOption('2');
  await page.getByRole('button',{name:'Save to my account',exact:true}).click();
  await page.getByText('Preferences saved to your account.',{exact:true}).waitFor();
  const crossSite=await context.request.put('http://127.0.0.1:3000/api/account',{headers:{origin:'https://attacker.example'},data:{preferences:{}}});
  assert.equal(crossSite.status(),400);
  await page.goto('http://127.0.0.1:3000/account');
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.waitForURL('http://127.0.0.1:3000/');
  await page.evaluate(()=>localStorage.clear());
  await page.goto('http://127.0.0.1:3000/account');
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in & continue'}).click();
  await page.waitForURL('**/preferences');
  assert.equal(await page.getByLabel('Noise',{exact:true}).inputValue(),'2');
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:3000');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'artifacts/improved-mobile.png',fullPage:false});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'artifacts/improved-desktop.png',fullPage:false});
  assert.deepEqual(errors,[]);
  console.log('PASS: 29 places, six preference choices, signup, review publish/persistence/delete, attribute stars, live attribute averages, rating-based preference ranking, deletion recalculation, saved preference restoration, logout, CSRF and mobile width.');
} finally {
  await browser.close();
  const db=new DatabaseSync('artifacts/community/community.sqlite');
  db.exec('PRAGMA foreign_keys=ON');
  db.prepare('DELETE FROM accounts WHERE username=?').run(username);
  db.close();
}
